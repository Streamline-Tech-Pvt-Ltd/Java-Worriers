package stack.in.main;

import java.util.Stack;

public class StackMethod {

	public static void main(String[] args) {
		Stack st = new Stack();
		st.add(1);
		st.add(2);
		st.add(3);
		st.push(6);
		st.push(7);
		st.push(9);
		System.out.println(st);
		System.out.println(st.peek());
		System.out.println(st);
		System.out.println(st.pop());
		System.out.println(st);
		
	
		

	}

}
